export function getViceByRoll(roll: number): string {
  const clamped = Math.max(1, Math.min(100, Math.floor(roll)));
  return NRI_VICES_D100[clamped - 1]!.text;
}

/** Бросок d100 по таблице пороков Carbon 2185. */
export function rollViceD100(rng: { int: (min: number, max: number) => number }): NriViceEntry {
  const roll = rng.int(1, 100);
  return { roll, text: getViceByRoll(roll) };
}
