function hashString(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

/** Хвост для реплики NPC: стабильный выбор по району + id, чтобы не повторять подряд один шаблон везде. */
export function literaryEchoTail(districtId: string, npcOrNodeId: string): string {
  const idx = hashString(`${districtId}|${npcOrNodeId}`) % CLAUSES.length;
  return CLAUSES[idx]!;
}

/** Хвост для описания квеста по id квеста и району. */
export function literaryEchoQuest(districtId: string, questId: string): string {
  const idx = hashString(`${districtId}|${questId}|quest`) % CLAUSES.length;
  return CLAUSES[idx]!;
}
